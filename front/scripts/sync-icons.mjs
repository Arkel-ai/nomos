// Regenerates src/lib/icons/solar.ts from scripts/icon-map.json.
//
// The app renders Solar icons through @iconify/svelte, which by default fetches
// icon data from api.iconify.design at runtime. We bundle instead: this script
// copies the -linear and -bold variants of every mapped icon out of
// @iconify-json/solar (a devDependency) into one committed module, so icons
// paint on first frame and the SPA keeps working offline.
//
// Run `npm run icons:sync` after editing scripts/icon-map.json.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');

const map = JSON.parse(readFileSync(resolve(here, 'icon-map.json'), 'utf8'));
const solar = JSON.parse(
	readFileSync(resolve(root, 'node_modules/@iconify-json/solar/icons.json'), 'utf8')
);

// Every distinct Solar base name the app asks for, deduplicated: several lucide
// names collapse onto one Solar icon (RotateCw/RotateCcw/RefreshCw -> refresh).
const bases = [...new Set(Object.entries(map).filter(([k]) => !k.startsWith('_')).map(([, v]) => v))].sort();

const icons = {};
const withBold = [];
const missing = [];

// Renamed icons survive as aliases (`code-file` -> `file-code`), so follow the
// chain before giving up on a name.
const resolve_ = (name) => {
	let seen = name;
	while (!solar.icons[seen] && solar.aliases?.[seen]) seen = solar.aliases[seen].parent;
	return solar.icons[seen];
};

for (const base of bases) {
	const linear = resolve_(`${base}-linear`);
	if (!linear) {
		missing.push(`${base}-linear`);
		continue;
	}
	icons[`${base}-linear`] = linear;
	// Not every Solar icon ships a bold cut (e.g. `plain`). Those stay linear
	// when active rather than silently rendering nothing.
	const bold = resolve_(`${base}-bold`);
	if (bold) {
		icons[`${base}-bold`] = bold;
		withBold.push(base);
	}
}

if (missing.length) {
	console.error(`Missing from @iconify-json/solar:\n  ${missing.join('\n  ')}`);
	process.exit(1);
}

const collection = {
	prefix: 'solar',
	icons,
	width: solar.width,
	height: solar.height
};

const out = `// GENERATED by \`npm run icons:sync\` — do not edit by hand.
// Source: scripts/icon-map.json + @iconify-json/solar@${
	JSON.parse(readFileSync(resolve(root, 'node_modules/@iconify-json/solar/package.json'), 'utf8'))
		.version
}
import { addCollection } from '@iconify/svelte';

/** Solar base names bundled for the app, without the style suffix. */
export type SolarIconName =
${bases.map((b) => `\t| '${b}'`).join('\n')};

/** Bases that ship a bold cut; the rest stay linear when active. */
export const boldIcons: ReadonlySet<string> = new Set(${JSON.stringify(withBold)});

addCollection(${JSON.stringify(collection)});
`;

mkdirSync(resolve(root, 'src/lib/icons'), { recursive: true });
writeFileSync(resolve(root, 'src/lib/icons/solar.ts'), out);

const kb = Math.round(Buffer.byteLength(out) / 1024);
console.log(
	`src/lib/icons/solar.ts — ${bases.length} icons (${withBold.length} with bold), ${Object.keys(icons).length} glyphs, ${kb}KB`
);
